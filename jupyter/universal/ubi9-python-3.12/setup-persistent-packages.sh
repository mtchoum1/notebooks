#!/bin/bash
# Sourced by entrypoint-universal.sh in workbench mode only.
# Redirects user package installs (pip and uv pip) to a PVC-backed prefix under
# $HOME so packages survive stop/start without writing into /opt/app-root.
#
# Nounset/errexit stay off so sourcing cannot abort notebook startup.
# Opt out: ODH_PERSISTENT_PACKAGES=0

if [ "${ODH_PERSISTENT_PACKAGES:-1}" = "0" ]; then
  # Drop managed uv config / shim so opt-out also affects uv.
  if [ -f "${HOME}/.config/uv/uv.toml" ] && grep -q "odh-persistent-packages" "${HOME}/.config/uv/uv.toml" 2>/dev/null; then
    rm -f "${HOME}/.config/uv/uv.toml"
  fi
  _opt_root="${ODH_PERSISTENT_PACKAGES_ROOT:-${HOME}/.local-packages}"
  if [ -f "${_opt_root}/uv.toml" ] && grep -q "odh-persistent-packages" "${_opt_root}/uv.toml" 2>/dev/null; then
    rm -f "${_opt_root}/uv.toml"
  fi
  rm -f "${_opt_root}/shim/uv"
  unset _opt_root
  return 0 2>/dev/null || exit 0
fi

_ODH_PERS_ROOT="${ODH_PERSISTENT_PACKAGES_ROOT:-${HOME}/.local-packages}"
# Pre-create lib and lib64 site-packages so the .pth bridge can addsitedir
# before the first install (pip --prefix uses lib64 on EL9). This image is
# Python 3.12 only (ubi9-python-3.12).
mkdir -p "${_ODH_PERS_ROOT}/bin" \
  "${_ODH_PERS_ROOT}/shim" \
  "${_ODH_PERS_ROOT}/lib/python3.12/site-packages" \
  "${_ODH_PERS_ROOT}/lib64/python3.12/site-packages"

export ODH_PERSISTENT_PACKAGES_ROOT="${_ODH_PERS_ROOT}"
# shim/ before bin/: wrapper named `uv` must win over the real binary in bin/.
export PATH="${_ODH_PERS_ROOT}/shim:${_ODH_PERS_ROOT}/bin${PATH:+:${PATH}}"
# PIP_PREFIX maps to pip install --prefix (does not mutate /opt/app-root).
export PIP_PREFIX="${_ODH_PERS_ROOT}"

# The base image sets UV_CONFIG_FILE=/opt/app-root/uv.toml which disables
# discovery of ~/.config/uv/uv.toml. Rewrite a managed config (image settings +
# PVC prefix) and point UV_CONFIG_FILE at it so `uv pip install` is persistent.
_ODH_UV_TOML="${_ODH_PERS_ROOT}/uv.toml"
{
  if [ -f /opt/app-root/uv.toml ]; then
    cat /opt/app-root/uv.toml
    printf '\n'
  fi
  cat <<EOF
# odh-persistent-packages — generated by setup-persistent-packages.sh; do not edit.
[pip]
prefix = "${_ODH_PERS_ROOT}"
EOF
} > "${_ODH_UV_TOML}"
# Keep a copy under XDG for tools that ignore UV_CONFIG_FILE.
mkdir -p "${HOME}/.config/uv"
cp -f "${_ODH_UV_TOML}" "${HOME}/.config/uv/uv.toml"
export UV_CONFIG_FILE="${_ODH_UV_TOML}"

# Catch-all shim: inject --prefix on uv pip install/uninstall/sync even if
# config is bypassed (--no-config) or VIRTUAL_ENV still points at /opt/app-root.
_ODH_UV_SHIM_SRC="/opt/app-root/bin/utils/odh-uv-shim.sh"
if [ -f "${_ODH_UV_SHIM_SRC}" ]; then
  install -m 0755 "${_ODH_UV_SHIM_SRC}" "${_ODH_PERS_ROOT}/shim/uv"
fi

# JupyterLab terminals start login shells that rebuild PATH from the image ENV
# and do not inherit these exports from the jupyter-lab process. Persist them
# on the PVC so terminals match notebook kernels.
_ODH_PERS_ENV="${_ODH_PERS_ROOT}/env.sh"
cat > "${_ODH_PERS_ENV}" <<EOF
# Generated by setup-persistent-packages.sh — do not edit.
export ODH_PERSISTENT_PACKAGES_ROOT="${_ODH_PERS_ROOT}"
export PIP_PREFIX="${_ODH_PERS_ROOT}"
export UV_CONFIG_FILE="${_ODH_UV_TOML}"
case ":\${PATH}:" in
  *":${_ODH_PERS_ROOT}/shim:"*) ;;
  *) export PATH="${_ODH_PERS_ROOT}/shim:${_ODH_PERS_ROOT}/bin\${PATH:+:\${PATH}}" ;;
esac
EOF
_ODH_PERS_MARKER="# odh-persistent-packages"
for _odh_profile in "${HOME}/.bashrc" "${HOME}/.profile"; do
  if [ ! -f "${_odh_profile}" ] || ! grep -q "odh-persistent-packages" "${_odh_profile}" 2>/dev/null; then
    printf '\n%s\n[ -f "%s" ] && . "%s"\n' \
      "${_ODH_PERS_MARKER}" "${_ODH_PERS_ENV}" "${_ODH_PERS_ENV}" >> "${_odh_profile}"
  fi
done

unset _ODH_PERS_ROOT _ODH_PERS_ENV _ODH_PERS_MARKER _odh_profile _ODH_UV_TOML _ODH_UV_SHIM_SRC
